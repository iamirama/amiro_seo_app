const SEV_W = { critical: 90, high: 70, medium: 50, low: 30, info: 10 } as const;
const EFFORT_W = { low: 0, medium: 6, high: 12 } as const;

function hash(value: string): string {
  let h = 2166136261;
  for (let i = 0; i < value.length; i += 1) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(16);
}

export function makeIssue(
  code: string,
  url: string | null,
  evidence: string,
  description: string,
  patch?: Partial<Issue>,
): Issue {
  const remedy = REMEDIES[code];
  if (!remedy) {
    throw new Error(`Missing remedy for ${code}`);
  }
  const severity = patch?.severity ?? remedy.severity;
  const effort = patch?.effort ?? remedy.effort;
  const confidence = patch?.confidence ?? remedy.confidence;
  return {
    id: `${code}:${hash(`${url ?? "site"}|${evidence.slice(0, 180)}`)}`,
    code,
    title: patch?.title ?? remedy.title,
    url,
    category: patch?.category ?? remedy.category,
    severity,
    confidence,
    description,
    why: remedy.why,
    evidence,
    solution: remedy.solution,
    steps: remedy.steps,
    example: remedy.example,
    docs: remedy.docs,
    effort,
    benefit: remedy.benefit,
    priority: SEV_W[severity] - EFFORT_W[effort] + (confidence === "high" ? 5 : 0),
    status: "open",
    source: patch?.source ?? remedy.source ?? "Northline crawl",
    heuristic: patch?.heuristic ?? remedy.heuristic,
  };
}
